#include <stdio.h>

int main()
{
    int i,j,n=5;
    for(i=1; i<=n;i++){
        for(j=1; j<=9;j++){
            if(i==1 || j==0+i || j==10-i){
                printf("*");
            }else{
                printf(" ");
            }
        }
    printf("\n");
}

    for(i=2; i<=n;i++){
        for(j=1; j<=9;j++){
            if(i==n || j==4+i || j==6-i){
                printf("*");
            }else{
                printf(" ");
            }
        }
    printf("\n");
}
    return 0;
}
